function setLanguage(lang) {
  const dict = LANGUAGES[lang] || LANGUAGES['es-MX'];
  // Navegación
  document.querySelector('a[data-i18n="nav_inicio"]').textContent = dict.nav_inicio;
  document.querySelector('a[data-i18n="nav_noticias"]').textContent = dict.nav_noticias;
  document.querySelector('a[data-i18n="nav_quienes"]').textContent = dict.nav_quienes;
  document.querySelector('a[data-i18n="nav_contacto"]').textContent = dict.nav_contacto;
  // Título y tagline
  document.querySelector('.titulo').textContent = dict.titulo;
  document.querySelector('.tagline').textContent = dict.tagline;
  // Banner principal
  document.querySelector('.banner-leyenda').textContent = dict.banner_leyenda;
  // Contacto
  document.querySelector('.contact-banner-social-title').textContent = dict.contactanos;
  document.querySelector('.contact-banner-social-tagline').textContent = dict.contact_tagline;
  document.querySelector('.contact-social-legend').textContent = dict.redes;
  document.querySelector('.donation-legend').textContent = dict.donar;
  document.querySelector('.donation-btn').innerHTML = `<img src="images/clip_logo.png" alt="Donar a KID-IA" class="donation-logo"> ${dict.donar_btn}`;
  document.querySelector('.contact-btn-main span').textContent = dict.ir_contacto;
  // Noticias
  document.querySelector('.news-carousel-header').textContent = dict.news_header;
  document.querySelector('.news-carousel-press-btn').textContent = dict.news_btn;
  // About
  document.querySelector('.about-banner-title').textContent = dict.quienes_titulo;
  document.querySelector('.about-banner-desc').textContent = dict.quienes_desc;
  document.querySelector('.about-banner-btn').textContent = dict.quienes_btn;
  // Footer
  document.querySelector('.footer p').textContent = dict.footer;
}

// Guardar preferencia en localStorage
document.addEventListener('DOMContentLoaded', function() {
  const select = document.getElementById('lang-select');
  if (select) {
    select.addEventListener('change', function() {
      localStorage.setItem('lang', select.value);
      setLanguage(select.value);
    });
    // Cargar preferencia guardada
    const saved = localStorage.getItem('lang');
    if (saved && LANGUAGES[saved]) {
      select.value = saved;
      setLanguage(saved);
    }
  }
});
